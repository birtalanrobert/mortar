import type { OutboundMessage } from './port';

/** Hosts a development stack runs on, whose unsubscribe link may be plain HTTP. */
const LOOPBACK = new Set(['localhost', '127.0.0.1', '[::1]']);

/** An address with nothing in it that could close the angle brackets it is written in. */
const PLAIN_ADDRESS = /^[^\s<>,@]+@[^\s<>,@]+$/;

/**
 * The headers an email carries besides its addresses and words, built once so
 * every email port writes them alike:
 *
 * - `X-Entity-Ref-ID`, our reference, which a provider's webhook and a bounce
 *   both quote back — how a receipt finds the message that caused it;
 * - `List-Unsubscribe` and `List-Unsubscribe-Post` (RFC 8058) for a message
 *   that may be stopped;
 * - `Auto-Submitted` (RFC 3834) and Exchange's `X-Auto-Response-Suppress` for
 *   one generated by software.
 *
 * Throws on an unsubscribe link that is not HTTPS — off a loopback host — or a
 * mail-to address that is not one: a link Gmail will not offer is a sender
 * failing its rules while believing it meets them.
 */
export function emailHeaders(message: OutboundMessage): Record<string, string> | undefined {
  const headers: Record<string, string> = {};
  if (message.reference) headers['X-Entity-Ref-ID'] = message.reference;
  if (message.unsubscribe) {
    const { url, mailto } = message.unsubscribe;
    const ways = [`<${unsubscribeUrl(url)}>`];
    if (mailto !== undefined) {
      if (!PLAIN_ADDRESS.test(mailto)) {
        throw new Error('The unsubscribe address is not an email address.');
      }
      ways.push(`<mailto:${mailto}?subject=unsubscribe>`);
    }
    headers['List-Unsubscribe'] = ways.join(', ');
    headers['List-Unsubscribe-Post'] = 'List-Unsubscribe=One-Click';
  }
  if (message.autoGenerated) {
    headers['Auto-Submitted'] = 'auto-generated';
    headers['X-Auto-Response-Suppress'] = 'OOF, AutoReply';
  }
  return Object.keys(headers).length > 0 ? headers : undefined;
}

function unsubscribeUrl(url: string): string {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    throw new Error('The unsubscribe link is not a URL.');
  }
  const secure =
    parsed.protocol === 'https:' || (parsed.protocol === 'http:' && LOOPBACK.has(parsed.hostname));
  if (!secure) throw new Error('The unsubscribe link must be HTTPS.');
  return parsed.href;
}
