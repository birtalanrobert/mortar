import { describe, expect, it } from 'vitest';
import { emailHeaders } from './email-headers';

const email = { channel: 'email' as const, to: 'ana@salon-aurora.ro', text: 'Hello.' };

describe('emailHeaders', () => {
  it('writes nothing for a message that asks for nothing', () => {
    expect(emailHeaders(email)).toBeUndefined();
  });

  it('offers a one-click way out, and an address to mail as well when given (RFC 8058)', () => {
    expect(
      emailHeaders({ ...email, unsubscribe: { url: 'https://example.com/unsubscribe/abc' } }),
    ).toEqual({
      'List-Unsubscribe': '<https://example.com/unsubscribe/abc>',
      'List-Unsubscribe-Post': 'List-Unsubscribe=One-Click',
    });
    expect(
      emailHeaders({
        ...email,
        unsubscribe: { url: 'https://example.com/unsubscribe/abc', mailto: 'leave@example.com' },
      })?.['List-Unsubscribe'],
    ).toBe('<https://example.com/unsubscribe/abc>, <mailto:leave@example.com?subject=unsubscribe>');
  });

  it('writes the link as a URL, so nothing in it can close its brackets', () => {
    expect(
      emailHeaders({ ...email, unsubscribe: { url: 'https://example.com/u/a b>c' } })?.[
        'List-Unsubscribe'
      ],
    ).toBe('<https://example.com/u/a%20b%3Ec>');
  });

  it('refuses a link Gmail would not offer: plain HTTP off a loopback host, or no URL at all', () => {
    expect(() =>
      emailHeaders({ ...email, unsubscribe: { url: 'http://example.com/unsubscribe/abc' } }),
    ).toThrow(/must be HTTPS/);
    expect(() => emailHeaders({ ...email, unsubscribe: { url: '/unsubscribe/abc' } })).toThrow(
      /not a URL/,
    );
    expect(() =>
      emailHeaders({
        ...email,
        unsubscribe: { url: 'https://example.com/u', mailto: 'leave@example.com>, <evil' },
      }),
    ).toThrow(/not an email address/);
  });

  it('lets a local stack link to itself over plain HTTP', () => {
    for (const host of ['localhost:4400', '127.0.0.1:4400', '[::1]:4400']) {
      expect(
        emailHeaders({ ...email, unsubscribe: { url: `http://${host}/u/abc` } })?.[
          'List-Unsubscribe'
        ],
      ).toBe(`<http://${host}/u/abc>`);
    }
  });

  it('marks a message software generated, for autoresponders and for Exchange (RFC 3834)', () => {
    expect(emailHeaders({ ...email, autoGenerated: true, reference: 'r:1' })).toEqual({
      'X-Entity-Ref-ID': 'r:1',
      'Auto-Submitted': 'auto-generated',
      'X-Auto-Response-Suppress': 'OOF, AutoReply',
    });
  });
});
